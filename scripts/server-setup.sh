#!/usr/bin/env bash
# network-tmp: server side. Run as root on the host that will hold the overflow.
#
# Creates a fixed-size ext4 image (hard cap: overflow can never fill the host's
# root disk), loop-mounts it, exports it over NFSv4 to the listed clients only,
# and installs an hourly cleanup timer that deletes anything untouched for TTL.
#
# Idempotent: re-running updates the export list and TTL; it never reformats an
# existing image. Resizing is a separate manual step (see README).
#
# Env (all optional):
#   NETTMP_SIZE     image size for a NEW image        default 100G
#   NETTMP_IMAGE    image file path                   default /var/lib/network-tmp/nettmp.img
#   NETTMP_EXPORT   mount point / export path         default /srv/nettmp
#   NETTMP_CLIENTS  space-separated client IPs/CIDRs  REQUIRED
#   NETTMP_TTL      age limit for scratch/            default 24h
#   NETTMP_KEEP_TTL age limit for keep/               default 7d
#   NETTMP_OWNER    uid:gid owning the tree           default 1000:1000
set -euo pipefail

SIZE="${NETTMP_SIZE:-100G}"
IMAGE="${NETTMP_IMAGE:-/var/lib/network-tmp/nettmp.img}"
EXPORT="${NETTMP_EXPORT:-/srv/nettmp}"
CLIENTS="${NETTMP_CLIENTS:?set NETTMP_CLIENTS to the client IPs, e.g. 100.64.0.10}"
TTL="${NETTMP_TTL:-24h}"
KEEP_TTL="${NETTMP_KEEP_TTL:-7d}"
OWNER="${NETTMP_OWNER:-1000:1000}"

[ "$(id -u)" = 0 ] || { echo "run as root" >&2; exit 1; }

say() { printf '[network-tmp] %s\n' "$*"; }

# 1. Image + filesystem. -m 0: no root reserve, it's scratch.
if [ ! -f "$IMAGE" ]; then
  mkdir -p "$(dirname "$IMAGE")"
  say "creating $SIZE image at $IMAGE"
  fallocate -l "$SIZE" "$IMAGE"
  mkfs.ext4 -q -F -m 0 -L nettmp "$IMAGE"
else
  say "image exists, leaving it ($(du -h --apparent-size "$IMAGE" | cut -f1))"
fi

# 2. Persistent loop mount.
mkdir -p "$EXPORT"
FSTAB_LINE="$IMAGE $EXPORT ext4 loop,noatime,nodev,nosuid 0 2"
if ! grep -qF " $EXPORT ext4 " /etc/fstab; then
  say "adding fstab entry"
  echo "$FSTAB_LINE  # network-tmp" >> /etc/fstab
  systemctl daemon-reload
fi
mountpoint -q "$EXPORT" || mount "$EXPORT"

# 3. Layout: scratch/ expires after TTL, keep/ after KEEP_TTL.
install -d -o "${OWNER%%:*}" -g "${OWNER##*:}" -m 0755 "$EXPORT/scratch" "$EXPORT/keep"
cat > "$EXPORT/README.txt" <<EOF
network-tmp overflow. NOT BACKED UP. Contents are deleted automatically:
  scratch/  anything untouched for $TTL
  keep/     anything untouched for $KEEP_TTL
Managed by https://github.com/danielrosehill/Claude-Network-Tmp-Plugin
EOF

# 4. NFS export, restricted to the named clients.
if ! dpkg -s nfs-kernel-server >/dev/null 2>&1; then
  say "installing nfs-kernel-server"
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq nfs-kernel-server >/dev/null
fi
mkdir -p /etc/exports.d
{
  echo "# network-tmp — generated by server-setup.sh, edit NETTMP_CLIENTS and re-run"
  for c in $CLIENTS; do
    echo "$EXPORT $c(rw,async,no_subtree_check,root_squash)"
  done
} > /etc/exports.d/network-tmp.exports
systemctl enable --now nfs-server >/dev/null 2>&1
exportfs -ra

# 5. Cleanup. tmpfiles 'e' = clean contents by age, never remove the dir itself.
# The "m:" prefix judges age on mtime only ("last written"). Without it,
# tmpfiles also counts atime and ctime, and ctime is bumped by chmod, mv and
# touch -d — so a file moved into keep/ or backdated for a test never expires
# on schedule. `nettmp clean` uses mtime too, so both agree.
cat > /etc/tmpfiles.d/network-tmp.conf <<EOF
# network-tmp — generated by server-setup.sh
e $EXPORT/scratch - - - m:$TTL
e $EXPORT/keep    - - - m:$KEEP_TTL
EOF

# The stock systemd-tmpfiles-clean.timer runs once a day, which lets a file
# live up to TTL+24h. Run our rules hourly instead.
cat > /etc/systemd/system/network-tmp-clean.service <<EOF
[Unit]
Description=network-tmp: delete expired overflow files
RequiresMountsFor=$EXPORT

[Service]
Type=oneshot
ExecStart=/usr/bin/systemd-tmpfiles --clean /etc/tmpfiles.d/network-tmp.conf
Nice=10
IOSchedulingClass=idle
EOF
cat > /etc/systemd/system/network-tmp-clean.timer <<'EOF'
[Unit]
Description=network-tmp: hourly cleanup

[Timer]
OnCalendar=hourly
Persistent=true
RandomizedDelaySec=5min

[Install]
WantedBy=timers.target
EOF
systemctl daemon-reload
systemctl enable --now network-tmp-clean.timer >/dev/null 2>&1

say "done"
df -h "$EXPORT" | tail -1
exportfs -v | grep -F "$EXPORT" || true
systemctl list-timers network-tmp-clean.timer --no-pager | sed -n 2p
