#!/usr/bin/env bash
# network-tmp: client side. Run as root on each machine that should overflow.
#
# Adds an on-demand (systemd automount) NFS mount of the server's export,
# writes /etc/network-tmp.conf, installs the `nettmp` helper to
# /usr/local/bin, and sets up a local-disk fallback directory that is cleaned
# on the same TTL.
#
# The mount is never permanent: it attaches on first access, detaches after
# 10 idle minutes, and gives up after 15 s if the server is unreachable — a
# hard, always-on NFS mount hangs every shell that touches it once the laptop
# is off the network.
#
# Env:
#   NETTMP_SERVER    server address (tailnet IP recommended)   REQUIRED
#   NETTMP_EXPORT    export path on the server       default /srv/nettmp
#   NETTMP_MOUNT     local mount point               default /mnt/nettmp
#   NETTMP_FALLBACK  local-disk fallback dir         default /var/tmp/network-tmp
#   NETTMP_TTL       fallback cleanup age            default 24h
#   NETTMP_LARGE_MB  "large file" threshold for the skills    default 50
set -euo pipefail

SERVER="${NETTMP_SERVER:?set NETTMP_SERVER to the server address}"
EXPORT="${NETTMP_EXPORT:-/srv/nettmp}"
MOUNT="${NETTMP_MOUNT:-/mnt/nettmp}"
FALLBACK="${NETTMP_FALLBACK:-/var/tmp/network-tmp}"
TTL="${NETTMP_TTL:-24h}"
LARGE_MB="${NETTMP_LARGE_MB:-50}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

[ "$(id -u)" = 0 ] || { echo "run as root" >&2; exit 1; }
say() { printf '[network-tmp] %s\n' "$*"; }

if ! dpkg -s nfs-common >/dev/null 2>&1; then
  say "installing nfs-common"
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq nfs-common >/dev/null
fi

cat > /etc/network-tmp.conf <<EOF
# network-tmp client config — generated by client-setup.sh
NETTMP_SERVER=$SERVER
NETTMP_EXPORT=$EXPORT
NETTMP_MOUNT=$MOUNT
NETTMP_FALLBACK=$FALLBACK
NETTMP_TTL=$TTL
NETTMP_LARGE_MB=$LARGE_MB
EOF

# soft + timeo=50,retrans=2: an I/O call fails with EIO after ~15 s instead of
# blocking forever when the server disappears mid-session. Acceptable for
# scratch data; never use these options for anything you can't lose.
OPTS="noauto,nofail,_netdev,x-systemd.automount,x-systemd.idle-timeout=10min,x-systemd.mount-timeout=15s,soft,timeo=50,retrans=2,noatime"
mkdir -p "$MOUNT"
sed -i "\| $MOUNT nfs4 |d" /etc/fstab
echo "$SERVER:$EXPORT $MOUNT nfs4 $OPTS 0 0  # network-tmp" >> /etc/fstab
systemctl daemon-reload
UNIT="$(systemd-escape -p --suffix=automount "$MOUNT")"
systemctl restart "$UNIT"

install -d -m 1777 "$FALLBACK"
cat > /etc/tmpfiles.d/network-tmp-fallback.conf <<EOF
# network-tmp local fallback — generated by client-setup.sh
d $FALLBACK 1777 root root $TTL
EOF

install -m 0755 "$HERE/nettmp" /usr/local/bin/nettmp
say "installed /usr/local/bin/nettmp"
say "automount: $UNIT ($(systemctl is-active "$UNIT"))"
